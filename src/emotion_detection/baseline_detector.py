DISPLAY_THRESHOLD = 0.06


def _normalize(text: str) -> str:
    text = text.lower().strip()
    text = re.sub(r"[^\w\s]", " ", text)
    text = re.sub(r"\s+", " ", text)
    return text


def expand_activities(text: str) -> str:
    t          = text.lower().strip()
    expansions = []
    for activity, expansion in ACTIVITY_MAP.items():
        if activity in t:
            # Guard against known substring collisions where an activity
            # phrase happens to appear inside an unrelated idiom, e.g.
            # "working out" (gym activity) matching inside "everything is
            # working out" (an idiom meaning things are going well).
            if activity == "working out" and "everything is working out" in t:
                continue
            expansions.append(expansion)
    if expansions:
        return t + " " + " ".join(expansions)
    return t


def expand_idioms(text: str) -> str:
    t          = text.lower().strip()
    expansions = []
    for idiom, expansion in IDIOM_MAP.items():
        if idiom in t:
            expansions.append(expansion)
    if expansions:
        return t + " " + " ".join(expansions)
    return t


def _detect_negations(text: str) -> set[str]:
    words   = text.lower().split()
    negated = set()
    for i, word in enumerate(words):
        clean_word = re.sub(r"[^\w]", "", word)
        if clean_word in NEGATION_WORDS:
            window      = words[i+1: i+1+NEGATION_WINDOW]
            window_text = " ".join(window)
            for emo, keywords in LEXICON.items():
                for kw in keywords:
                    if kw in window_text:
                        negated.add(emo)
                        break
    return negated


DOMINANCE_PATTERNS = [
    "but im more", "but i'm more", "but more",
    "mostly", "mainly", "primarily",
    "leaning towards", "leaning more", "leaning toward",
    "is stronger", "is the stronger one",
    "more than anything", "above all",
    "but really", "but honestly im", "but honestly i'm",
]

DOMINANCE_BOOST = 1


def _detect_dominance_boost(text: str) -> str | None:
    t = text.lower()
    words = t.split()

    for i, word in enumerate(words):
        for pattern in DOMINANCE_PATTERNS:
            pattern_words = pattern.split()
            window = words[i:i + len(pattern_words) + 4]
            window_text = " ".join(window)
            if pattern in window_text:
                after_pattern = window_text.split(pattern, 1)[-1]
                for emo, keywords in LEXICON.items():
                    for kw in keywords:
                        if kw in after_pattern:
                            return emo
    return None


def predict_emotion(text: str) -> tuple[str, dict[str, float]]:
    expanded = expand_activities(text)
    expanded = expand_idioms(expanded)
    t        = _normalize(expanded)

    # Negation must be detected on the ORIGINAL text only, never on text
    # that has already been expanded by idiom/activity mapping. Otherwise
    # a negation trigger word (e.g. "cant", "dont") earlier in the sentence
    # can accidentally scoop up an emotion word that the expansion system
    # itself injected later in the string, incorrectly treating it as the
    # thing being negated (e.g. "cant cope" expanding to include the word
    # "stressed" from its own idiom match, which then gets wrongly read
    # as "cant [be] stressed" and flipped to calm).
    original_normalized = _normalize(text)

    scores = Counter({e: 0 for e in EMOTIONS})

    for emo, keywords in LEXICON.items():
        for kw in keywords:
            if kw in t:
                weight = 3 if len(kw.split()) >= 3 else 2 if " " in kw else 1
                scores[emo] += weight

    if "!" in text:
        scores["excited"] += 1
    intensifiers = [
        "so ", "very ", "really ", "extremely ", "super ",
        "genuinely ", "literally ", "actually ", "lowkey ",
        "highkey ", "fr ", "deadass ",
    ]
    if any(x in t for x in intensifiers):
        for emo in EMOTIONS:
            if scores[emo] > 0:
                scores[emo] += 1

    # Negation must scan the ORIGINAL text only, never the expanded text,
    # so an emotion word injected by idiom/activity expansion later in the
    # string can never be wrongly treated as the thing being negated.
    negated_emotions = _detect_negations(original_normalized)
    for neg_emo in negated_emotions:
        if scores[neg_emo] > 0:
            penalty         = scores[neg_emo]
            scores[neg_emo] = max(0, scores[neg_emo] - penalty)
            flip_emo        = NEGATION_FLIPS.get(neg_emo)
            if flip_emo:
                scores[flip_emo] += penalty

    pre_boost_scores = dict(scores)

    dominant_signal = _detect_dominance_boost(t)
    boosted_scores  = dict(scores)
    if dominant_signal and dominant_signal in boosted_scores:
        boosted_scores[dominant_signal] += DOMINANCE_BOOST

    if sum(pre_boost_scores.values()) == 0:
        return "neutral", {"neutral": 1.0}

    tie_priority = [
        "sad", "anxious", "stressed", "angry", "romance",
        "motivated", "calm", "happy", "excited", "neutral",
    ]
    max_score  = max(boosted_scores.values())
    candidates = [e for e, s in boosted_scores.items() if s == max_score]
    dominant   = sorted(
        candidates,
        key=lambda x: tie_priority.index(x) if x in tie_priority else 99
    )[0]

    display_scores = dict(pre_boost_scores)
    if dominant_signal and dominant_signal == dominant:
        display_scores[dominant_signal] += DOMINANCE_BOOST

    total     = sum(display_scores.values())
    raw_probs = {e: display_scores[e] / total for e in EMOTIONS}

    filtered = {
        e: p for e, p in raw_probs.items()
        if pre_boost_scores.get(e, 0) > 0 and p >= DISPLAY_THRESHOLD
    }
    if dominant not in filtered:
        filtered[dominant] = raw_probs.get(dominant, 1.0)

    filt_total = sum(filtered.values())
    probs      = {e: filtered[e] / filt_total for e in filtered}

    return dominant, probs